// ------------------------------------------------------------------ idiomas

export const LANGS = [
  { id: "es", name: "Español", dict: es },
  { id: "en", name: "English", dict: en },
  { id: "pt", name: "Português", dict: pt },
  { id: "fr", name: "Français", dict: fr },
  { id: "de", name: "Deutsch", dict: de },
  { id: "it", name: "Italiano", dict: it },
  { id: "ru", name: "Русский", dict: ru },
  { id: "zh", name: "中文", dict: zh },
  { id: "ja", name: "日本語", dict: ja },
] as const;

export type LangId = (typeof LANGS)[number]["id"];

export const getDict = (id: string): Dict => LANGS.find((l) => l.id === id)?.dict ?? es;

/** Idioma del sistema si está soportado; si no, español. */
export function detectLang(): LangId {
  const sys = (typeof navigator !== "undefined" ? navigator.language : "es").slice(0, 2).toLowerCase();
  return (LANGS.find((l) => l.id === sys)?.id ?? "es") as LangId;
}

// ------------------------------------------------------------------ React

interface I18n { t: Dict; lang: string }
const Ctx = createContext<I18n>({ t: es, lang: "es" });

export function I18nProvider({ lang, children }: { lang: string; children: React.ReactNode }) {
  return <Ctx.Provider value={{ t: getDict(lang), lang }}>{children}</Ctx.Provider>;
}

/** Textos del idioma actual: `const { t, lang } = useT()`. */
export const useT = () => useContext(Ctx);
